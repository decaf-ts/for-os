/**
 * @module for-os.notifications
 * @description Desktop-notification bridge with timers and JavaScript action callbacks.
 * @summary `NotificationCenter` sends notifications through the native addon,
 * exposes action buttons as JavaScript callbacks, and owns the auto-dismiss
 * timer contract. Button delivery is native on Linux (through
 * `notify-send --wait`); macOS and Windows render a plain notification and
 * report that no buttons are available.
 */

import { ValidationError } from "@decaf-ts/db-decorators";
import { NativeModuleUnavailableError } from "../errors";
import { loadNativeModule, requireNativeModule } from "../native/loader";
import type { NativeModule, NativeNotificationAction } from "../native/types";

/** Default auto-dismiss delay for a notification, in milliseconds. */
export const DEFAULT_NOTIFICATION_TIMEOUT_MS = 10_000;

/** Interval of the cooperative native action poll, in milliseconds. */
const DEFAULT_POLL_INTERVAL_MS = 100;

/** Callback invoked when a notification action or button is activated. */
export type NotificationActionHandler = (
  actionId: string,
  notification?: NotificationRecord
) => void;

/**
 * One action button rendered on a notification.
 * @summary Button ids match literally. The `default` action id emitted by the
 * native service for a notification-body click is reserved: it resolves to the
 * first button of the owning notification unless a button is explicitly named
 * `default`.
 */
export type NotificationButton = {
  /** Stable id reported to the handler. */
  id: string;
  /** Button label rendered by the operating system. */
  label: string;
  /** Optional per-button callback. */
  onClick?: NotificationActionHandler;
};

/** Reason a notification is considered dismissed. */
export type DismissReason = "timer" | "manual";

/** Public state of a dispatched notification. */
export type NotificationRecord = {
  /** Stable id generated by the bridge. */
  readonly id: string;
  readonly title: string;
  readonly body: string;
  /** Configured auto-dismiss delay; `0` disables the timer. */
  readonly timeoutMs: number;
  /** Action buttons captured at dispatch; treat this array as read-only. */
  readonly buttons: NotificationButton[];
  /** Whether the operating system accepted the notification. */
  readonly delivered: boolean;
  /** Whether the timer or a manual call marked the notification dismissed. */
  readonly dismissed: boolean;
  /** Marks the notification dismissed and invokes `onDismiss` once. */
  dismiss(reason?: DismissReason): void;
  /** Registers an additional action handler for this notification. */
  onAction(handler: NotificationActionHandler): NotificationRecord;
};

/** Options accepted by {@link NotificationCenter.notify}. */
export type NotifyOptions = {
  title: string;
  body: string;
  /**
   * Auto-dismiss delay in milliseconds. Defaults to
   * {@link DEFAULT_NOTIFICATION_TIMEOUT_MS}; `0` disables the timer. The native
   * host requests the delay where its notification service supports expiry
   * (Linux, Windows); the OS may override it. macOS uses its system policy.
   * Zero is forwarded to native code and disables the local timer.
   */
  timeoutMs?: number;
  /** Action buttons; native delivery is Linux-only. */
  buttons?: NotificationButton[];
  /** Notification-level action callback. */
  onAction?: NotificationActionHandler;
  /** Called once when the timer fires or {@link NotificationRecord.dismiss} runs. */
  onDismiss?: (reason: DismissReason, notification: NotificationRecord) => void;
};

/** Construction options for {@link NotificationCenter}. */
export type NotificationCenterOptions = {
  /** Native module override (tests/embedding); defaults to the built addon. */
  api?: NativeModule;
  /** Global action dispatch interval (defaults to 100 ms). */
  pollIntervalMs?: number;
  /** Best-effort diagnostics sink. */
  log?: (message: string) => void;
};

type InternalRecord = NotificationRecord & {
  actionHandlers: Set<NotificationActionHandler>;
  dismissHandlers: Array<(reason: DismissReason, notification: NotificationRecord) => void>;
  timer?: ReturnType<typeof setTimeout>;
};

function defaultLog(message: string): void {
  console.warn(message);
}

function validate(options: NotifyOptions): void {
  if (!options || typeof options !== "object") {
    throw new ValidationError("Notification options are required.");
  }
  if (typeof options.title !== "string" || !options.title.trim()) {
    throw new ValidationError("Notification title is required.");
  }
  if (typeof options.body !== "string" || !options.body.trim()) {
    throw new ValidationError("Notification body is required.");
  }
  if (
    options.timeoutMs !== undefined &&
    (!Number.isFinite(options.timeoutMs) || options.timeoutMs < 0)
  ) {
    throw new ValidationError("Notification timeoutMs must be a finite number >= 0.");
  }
  const ids = new Set<string>();
  for (const button of options.buttons ?? []) {
    if (!button?.id || !button?.label) {
      throw new ValidationError("Every notification button requires an id and a label.");
    }
    if (ids.has(button.id)) {
      throw new ValidationError(`Duplicate notification button id "${button.id}".`);
    }
    ids.add(button.id);
  }
}

/**
 * @description Sends native notifications and maps their buttons to JavaScript callbacks.
 * @summary Use one centre per process. Action ids are matched against
 * registered global handlers, the notification's own `onAction`, and each
 * button's `onClick`. An id that matches no live notification reaches global
 * handlers only, and dismissed notifications are pruned from the record set.
 * The reserved `default` body-click id maps to the owning notification's first
 * button. `close()` clears the timer and poll loop.
 * @param {NotificationCenterOptions} [options] native module override, poll
 * interval, and diagnostics sink
 * @class NotificationCenter
 * @example
 * import { NotificationCenter } from "@decaf-ts/for-os";
 * const center = new NotificationCenter();
 * const notification = center.notify({
 *   title: "Build finished",
 *   body: "The native addon is ready.",
 *   timeoutMs: 5000,
 *   buttons: [{ id: "open", label: "Open" }],
 * });
 * notification.onAction((actionId) => console.log(actionId));
 * center.close();
 */
export class NotificationCenter {
  private readonly api?: NativeModule;
  private readonly pollIntervalMs: number;
  private readonly log: (message: string) => void;
  private readonly globalHandlers = new Map<string, Set<NotificationActionHandler>>();
  private readonly records: InternalRecord[] = [];
  private poll?: ReturnType<typeof setInterval>;
  private counter = 0;
  private closed = false;

  constructor(options: NotificationCenterOptions = {}) {
    this.api = options.api;
    this.pollIntervalMs = options.pollIntervalMs ?? DEFAULT_POLL_INTERVAL_MS;
    this.log = options.log ?? defaultLog;
  }

  /** Whether a native notification backend is available. */
  get available(): boolean {
    if (this.api) return true;
    return loadNativeModule().available;
  }

  private native(): NativeModule {
    if (this.closed) {
      throw new NativeModuleUnavailableError("The notification centre is closed.");
    }
    if (this.api) return this.api;
    return requireNativeModule();
  }

  /**
   * Registers a global handler for an action id.
   * @param {string} id action id
   * @param {NotificationActionHandler} handler callback
   * @return {NotificationCenter} this instance
   */
  registerAction(id: string, handler: NotificationActionHandler): this {
    const handlers = this.globalHandlers.get(id) ?? new Set<NotificationActionHandler>();
    handlers.add(handler);
    this.globalHandlers.set(id, handlers);
    return this;
  }

  /**
   * Removes a global action handler.
   * @param {string} id action id
   * @param {NotificationActionHandler} handler callback
   * @return {NotificationCenter} this instance
   */
  unregisterAction(id: string, handler: NotificationActionHandler): this {
    this.globalHandlers.get(id)?.delete(handler);
    return this;
  }

  /**
   * Sends a notification and returns its handle.
   * @param {NotifyOptions} options title, body, timer, and buttons
   * @return {NotificationRecord} the dispatched notification
   * @throws {ValidationError} for missing title/body or invalid options
   * @throws {NativeModuleUnavailableError} when no native backend is available
   */
  notify(options: NotifyOptions): NotificationRecord {
    validate(options);
    const api = this.native();
    const timeoutMs = options.timeoutMs ?? DEFAULT_NOTIFICATION_TIMEOUT_MS;
    const buttons = [...(options.buttons ?? [])];
    const record = this.createRecord(options, timeoutMs, buttons, true);
    try {
      const actions: NativeNotificationAction[] = buttons.map((button) => ({
        id: button.id,
        label: button.label,
      }));
      if (actions.length && api.showNotificationWithActions) {
        api.showNotificationWithActions(
          options.title,
          options.body,
          actions,
          timeoutMs
        );
      } else {
        api.showNotification(
          options.title,
          options.body,
          timeoutMs
        );
      }
    } catch (error) {
      this.removeRecord(record);
      throw error;
    }
    this.startPoll();
    return record;
  }

  /**
   * Sends an appointment-style notification with Accept and See buttons.
   * @param {Omit<NotifyOptions, "buttons">} options notification content
   * @return {NotificationRecord} the dispatched notification
   */
  notifyAppointment(options: Omit<NotifyOptions, "buttons">): NotificationRecord {
    const api = this.native();
    if (!api.showAppointmentNotification) {
      return this.notify({
        ...options,
        buttons: [
          { id: "accept", label: "Accept appointment" },
          { id: "see", label: "See appointment" },
        ],
      });
    }
    validate(options);
    const timeoutMs = options.timeoutMs ?? DEFAULT_NOTIFICATION_TIMEOUT_MS;
    const buttons: NotificationButton[] = [
      { id: "accept", label: "Accept appointment" },
      { id: "see", label: "See appointment" },
    ];
    const record = this.createRecord(options, timeoutMs, buttons, true);
    try {
      api.showAppointmentNotification(
        options.title,
        options.body,
        timeoutMs
      );
    } catch (error) {
      this.removeRecord(record);
      throw error;
    }
    this.startPoll();
    return record;
  }

  /**
   * Drains pending native actions immediately.
   * @return {string[]} action ids dispatched in this drain
   */
  pollActions(): string[] {
    const api = this.api ?? (loadNativeModule().available ? requireNativeModule() : undefined);
    if (!api?.pollNotificationActions) return [];
    const dispatched: string[] = [];
    try {
      for (let action = api.pollNotificationActions(); action; action = api.pollNotificationActions()) {
        this.dispatch(action);
        dispatched.push(action);
      }
    } catch (error) {
      this.log(
        `for-os: notification action poll failed (${error instanceof Error ? error.message : String(error)}).`
      );
    }
    return dispatched;
  }

  /** Clears timers, the poll loop, and retained notification records. */
  close(): void {
    if (this.closed) return;
    this.closed = true;
    if (this.poll) clearInterval(this.poll);
    this.poll = undefined;
    for (const record of [...this.records]) {
      if (record.timer) clearTimeout(record.timer);
      this.records.splice(this.records.indexOf(record), 1);
    }
  }

  private createRecord(
    options: NotifyOptions,
    timeoutMs: number,
    buttons: NotificationButton[],
    delivered: boolean
  ): InternalRecord {
    const id = `for-os-notification-${++this.counter}`;
    const record: InternalRecord = {
      id,
      title: options.title,
      body: options.body,
      timeoutMs,
      buttons,
      delivered,
      dismissed: false,
      actionHandlers: new Set<NotificationActionHandler>(),
      dismissHandlers: [],
      dismiss: () => undefined,
      onAction: () => record,
    };
    record.dismiss = (reason: DismissReason = "manual") => this.dismiss(record, reason);
    record.onAction = (handler: NotificationActionHandler) => {
      record.actionHandlers.add(handler);
      return record;
    };
    if (options.onAction) record.actionHandlers.add(options.onAction);
    if (options.onDismiss) record.dismissHandlers.push(options.onDismiss);
    if (timeoutMs > 0) {
      record.timer = setTimeout(() => this.dismiss(record, "timer"), timeoutMs);
      record.timer.unref?.();
    }
    this.records.push(record);
    return record;
  }

  private dismiss(record: InternalRecord, reason: DismissReason): void {
    if (record.dismissed) return;
    (record as { dismissed: boolean }).dismissed = true;
    if (record.timer) clearTimeout(record.timer);
    for (const handler of record.dismissHandlers) {
      try {
        handler(reason, record);
      } catch (error) {
        this.log(
          `for-os: notification dismiss handler failed (${error instanceof Error ? error.message : String(error)}).`
        );
      }
    }
    this.removeRecord(record);
  }

  private removeRecord(record: InternalRecord): void {
    if (record.timer) clearTimeout(record.timer);
    const index = this.records.indexOf(record);
    if (index >= 0) this.records.splice(index, 1);
  }

  private dispatch(actionId: string): void {
    const record = this.findRecord(actionId);
    const handlers = this.globalHandlers.get(actionId);
    if (handlers) {
      for (const handler of handlers) this.invoke(actionId, record, handler);
    }
    if (!record) return;
    const recordAction =
      actionId === "default" && !record.buttons.some((button) => button.id === "default")
        ? (record.buttons[0]?.id ?? actionId)
        : actionId;
    for (const handler of record.actionHandlers) this.invoke(recordAction, record, handler);
    const button = record.buttons.find((candidate) => candidate.id === recordAction);
    if (button?.onClick) this.invoke(recordAction, record, button.onClick);
  }

  private findRecord(actionId: string): InternalRecord | undefined {
    for (let index = this.records.length - 1; index >= 0; index--) {
      const record = this.records[index];
      if (record.buttons.some((button) => button.id === actionId)) return record;
    }
    if (actionId === "default") {
      for (let index = this.records.length - 1; index >= 0; index--) {
        if (this.records[index].buttons.length) return this.records[index];
      }
    }
    return undefined;
  }

  private invoke(
    actionId: string,
    record: NotificationRecord | undefined,
    handler: NotificationActionHandler
  ): void {
    try {
      handler(actionId, record);
    } catch (error) {
      this.log(
        `for-os: notification action "${actionId}" handler failed (${error instanceof Error ? error.message : String(error)}).`
      );
    }
  }

  private startPoll(): void {
    if (this.poll || this.closed) return;
    this.poll = setInterval(() => this.pollActions(), this.pollIntervalMs);
    this.poll.unref?.();
  }
}

/**
 * Sends one notification through a short-lived default centre.
 * @param {NotifyOptions} options notification content
 * @return {NotificationRecord} the dispatched notification
 */
export function notify(options: NotifyOptions): NotificationRecord {
  return new NotificationCenter().notify(options);
}
